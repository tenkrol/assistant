/**
 * E4: отличить запрос на изменение продукта от обычной задачи.
 *
 * Без модели и сети: строгий шаблон «глагол изменения + продуктовая область».
 * Неоднозначное остаётся обычным сообщением.
 */
const CHANGE = /(^|\s)(добав|измен|доработ|убери|удали|переделай|сделай так,? чтобы|нужно чтобы|надо чтобы|хочу чтобы)/i
const PRODUCT = /(бот|агент|команд|панел|интерфейс|функци|возможност|приложен|мини-прилож|сценари|напомин|календар)/i

export function looksLikeChangeRequest(text) {
  const clean = String(text ?? '').trim()
  if (clean.length < 8 || clean.length > 2000) return false
  return CHANGE.test(clean) && PRODUCT.test(clean)
}
