/**
 * Режимы ответа: один общий модуль вместо маршрутизатора команд.
 *
 * Проверяется главное: `MODES` живёт в `core/modes.mjs`, маршрутизатор команд
 * реэкспортирует тот же объект (прежние импорты не ломаются), а тексты режимов
 * остались дословными.
 */
import assert from 'node:assert/strict'
import test from 'node:test'
import { MODES } from '../src/core/modes.mjs'
import { MODES as MODES_FROM_COMMANDS } from '../src/core/commands.mjs'

test('режимы живут в core/modes.mjs, а commands их реэкспортирует', () => {
  assert.equal(MODES_FROM_COMMANDS, MODES, 'это тот же объект, а не копия')
  assert.deepEqual(Object.keys(MODES), ['кратко', 'подробно', 'код', 'письмо', 'просто'])
})

test('описания режимов не изменились', () => {
  assert.equal(MODES['кратко'], 'Отвечай очень коротко: 1–3 предложения, без вступлений и итогов.')
  assert.equal(MODES['подробно'], 'Отвечай подробно: структура, примеры, при необходимости список шагов.')
  assert.equal(MODES['код'], 'Отвечай как программист: только код и краткие пояснения к нему, без воды.')
  assert.equal(MODES['письмо'], 'Пиши в деловом стиле, готовым текстом письма, без разговорных выражений.')
  assert.equal(MODES['просто'], 'Объясняй простыми словами, без технического жаргона.')
})
